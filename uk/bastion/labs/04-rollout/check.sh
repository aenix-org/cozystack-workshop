#!/usr/bin/env bash
# Перевірка лаби 4: викочування нової версії та відкат.
#
# Перевіряємо суть, а не набрані команди:
#   - в історії застосунку є кілька ревізій, тобто версію справді змінювали;
#   - ConfigMap другої версії лежить у кластері окремим об'єктом, а не правкою першого;
#   - у контейнера є readinessProbe — без неї нульовий простій невідтворний;
#   - викочування доведене до кінця, а не застрягло;
#   - сторінка, яку віддає Service, відповідає тому ConfigMap, на який
#     посилається опис. Це ловить випадок «опис відкотили, а Pod не перестворилися».
#
# Скрипт нічого не змінює. Одноразовий Pod потрібен лише щоб забрати сторінку
# зсередини кластера і прибирає себе сам.
#
# Запускається на віртуалці, з теки цієї лаби, за доступом до навчального кластера `lab`
# (не до тенанта на кластері керування):
#     export KUBECONFIG=~/lab.kubeconfig
#     cd labs/04-rollout && ./check.sh
# Змінна COZY_TENANT тут не потрібна: вся лаба йде всередині кластера `lab`.
#
# Запускати ДО прибирання і після того, як відкат завершився: історія ревізій живе
# разом із Deployment, і разом із ним же зникає.

# Потрапляють у заголовок звіту і в ім'я файлу report-<лаба>-<дата>.md поруч зі скриптом.
LAB_NAME="04-rollout"
LAB_TITLE="Лаба 4 · Викочування нової версії та відкат"
# Спільна бібліотека: ok / fail / warn / evidence / finish, запити зсередини кластера,
# запис звіту. Шлях рахується від місця самого скрипта, а не від поточного каталогу.
. "$(cd "$(dirname "$0")/../../check" && pwd)/lib.sh"

# Без KUBECONFIG kubectl шукає кластер на віртуалці і валить усе поспіль однією помилкою,
# у якій справжньої причини не розгледіти. Зупиняємося одразу.
need_kubeconfig

APP=rickroll

# --- застосунок на місці і доведений до робочого стану ------------------
# Без застосунку перевіряти нічого, тому тут єдиний достроковий вихід.
# Далі дивимося не лише на число готових копій, а й на причину в умові
# Progressing: NewReplicaSetAvailable означає, що викочування ЗАВЕРШЕНЕ. Самих
# готових копій мало — при застряглому оновленні працює стара версія, лічильник
# показує потрібне число, а нова копія при цьому не піднялася жодного разу.
if ! kubectl get deployment "$APP" >/dev/null 2>&1; then
  fail "застосунку ${APP} немає в кластері" \
       "розгорніть його: kubectl apply -f ../01-deploy/rickroll.yaml"
  finish
  exit $?
fi

WANT="$(kubectl get deployment "$APP" -o jsonpath='{.spec.replicas}' 2>/dev/null)"
HAVE="$(kubectl get deployment "$APP" -o jsonpath='{.status.readyReplicas}' 2>/dev/null)"
[ -z "$HAVE" ] && HAVE=0

PROG_REASON="$(kubectl get deployment "$APP" \
  -o jsonpath='{range .status.conditions[?(@.type=="Progressing")]}{.reason}{end}' 2>/dev/null)"

if [ "$HAVE" = "$WANT" ] && [ "${HAVE:-0}" -ge 1 ] && [ "$PROG_REASON" = "NewReplicaSetAvailable" ]; then
  ok "викочування доведене до кінця: готових копій ${HAVE} з ${WANT}"
else
  fail "застосунок не в завершеному стані (готово ${HAVE} з ${WANT}, причина: ${PROG_REASON:-немає})" \
       "якщо викочування застрягло — вийдіть відкатом: kubectl rollout undo deployment/${APP}"
fi
evidence "Стан застосунку" "$(kubectl get deployment,rs,pods -l app=${APP} 2>/dev/null)"

# --- readinessProbe: те, чим оплачений нульовий простій -----------------------
PROBE="$(kubectl get deployment "$APP" \
  -o jsonpath='{.spec.template.spec.containers[0].readinessProbe.httpGet.path}' 2>/dev/null)"
if [ -n "$PROBE" ]; then
  ok "у контейнера є readinessProbe (${PROBE}) — заміна копій іде тільки після готовності"
else
  fail "у контейнера немає readinessProbe" \
       "без неї кластер пускає трафік на неготову копію; застосуйте ../01-deploy/rickroll.yaml"
fi

# --- версії зроблені різними об'єктами --------------------------------------
# Обидві версії сторінки мають лежати в кластері як два окремих ConfigMap.
# Той, хто замість цього виправив rickroll-page-v1 на місці, побачить на екрані
# нову сторінку і вирішить, що лаба зроблена, — але відкочуватися йому буде нікуди,
# а заміни копій і запису в історії ревізій не станеться зовсім.
if kubectl get configmap rickroll-page-v2 >/dev/null 2>&1; then
  ok "ConfigMap rickroll-page-v2 лежить у кластері окремим об'єктом"
else
  fail "у кластері немає ConfigMap rickroll-page-v2" \
       "застосуйте його: kubectl apply -f rickroll-page-v2.yaml"
fi

if kubectl get configmap rickroll-page-v1 >/dev/null 2>&1; then
  ok "перша версія сторінки теж збережена — є куди відкочуватися"
else
  warn "ConfigMap rickroll-page-v1 у кластері не знайдено" \
       "відкат на першу версію без нього не підійме Pod: kubectl apply -f ../01-deploy/rickroll.yaml"
fi

# --- історія ревізій -------------------------------------------------------
# Дивимося НОМЕР останньої ревізії, а не кількість рядків в історії. Відкат не
# додає новий ReplicaSet — він перевикористовує старий і підвищує його номер,
# тому рядків в історії після відкату стільки ж, а номер зростає.
#   1 — опис жодного разу не змінювали
#   2 — версію перемкнули
#   3 і більше — перемкнули і повернули
REV_MAX="$(kubectl rollout history deployment/${APP} 2>/dev/null \
  | awk '$1 ~ /^[0-9]+$/ { if ($1+0 > m) m = $1+0 } END { print m+0 }')"
[ -z "$REV_MAX" ] && REV_MAX=0

if [ "$REV_MAX" -ge 3 ]; then
  ok "остання ревізія застосунку — ${REV_MAX}: версію перемикали і повертали"
elif [ "$REV_MAX" -eq 2 ]; then
  warn "остання ревізія — 2: викочування зроблене, відкату ще немає" \
       "поверніть першу версію: kubectl rollout undo deployment/${APP}"
else
  fail "остання ревізія — ${REV_MAX}: опис застосунку жодного разу не змінювався" \
       "перемкніть том на другу версію патчем із лаби, потім відкотіться"
fi
evidence "Історія ревізій" "$(kubectl rollout history deployment/${APP} 2>/dev/null)"

# --- на яку версію дивиться опис --------------------------------------
# Том шукаємо ЗА ІМЕНЕМ page, хоча патч у лабі адресує його номером. Різниця тут
# і ловиться: якщо патч пішов не в той елемент списку, ім'я page буде вказувати
# на попередній ConfigMap або зникне, і учасник дізнається про це словами, а не
# за дивною помилкою nginx.
VOL_CM="$(kubectl get deployment "$APP" \
  -o jsonpath='{range .spec.template.spec.volumes[?(@.name=="page")]}{.configMap.name}{end}' 2>/dev/null)"

case "$VOL_CM" in
  rickroll-page-v1)
    ok "опис застосунку повернуто на першу версію сторінки"
    ;;
  rickroll-page-v2)
    warn "опис застосунку вказує на другу версію сторінки" \
         "лаба закінчується відкатом; якщо так і задумано — нічого страшного, інакше: kubectl rollout undo deployment/${APP}"
    ;;
  "")
    fail "в описі немає тома з іменем page" \
         "схоже, патч потрапив не туди (адресація за номером!); застосуйте ../01-deploy/rickroll.yaml заново"
    ;;
  *)
    fail "том page вказує на ConfigMap ${VOL_CM}, якого лаба не створювала" \
         "відкотіться: kubectl rollout undo deployment/${APP}"
    ;;
esac

# --- що реально віддається клієнту ------------------------------------------
# Найзмістовніша перевірка: звіряємо опис із тим, що бачить користувач.
# Розбіжність тут означає, що Pod не перестворилися під новий опис.
# Вісім запитів, а не один. За сервісом три копії; якщо викочування зійшлося не до кінця,
# єдиний запит з імовірністю в третину потрапить на потрібну версію і сховає розбіжність.
BODIES="$(in_cluster_curl_many "http://${APP}/" 8)"
BODY="$BODIES"

if [ -z "$BODY" ]; then
  fail "Service ${APP} не віддав сторінку зсередини кластера" \
       "перевірте ендпоінти: kubectl get endpointslices -l kubernetes.io/service-name=${APP}"
else
  # Обидві версії визначаємо ПОЗИТИВНО, за своїм маркером. Гілка «якщо не v2, значить
  # v1» зараховувала за першу версію будь-що: дефолтну сторінку nginx, 404, чужий
  # застосунок, сміття — перевірено, на смітті скрипт видавав «ЛАБУ СКЛАДЕНО».
  if printf '%s' "$BODY" | grep -q 'ВЕРСІЯ 2'; then
    SERVED_VER="rickroll-page-v2"
  elif printf '%s' "$BODY" | grep -q 'Never Gonna Give You Up'; then
    SERVED_VER="rickroll-page-v1"
  else
    SERVED_VER=""
    fail "за адресою сервісу віддається не сторінка застосунку" \
         "жодного знайомого маркера у відповіді — поверніть початкове: kubectl apply -f ../01-deploy/rickroll.yaml"
    evidence "Що повернулося замість сторінки" "$(printf '%s' "$BODY" | head -12)"
  fi

  if [ -n "$VOL_CM" ] && [ "$SERVED_VER" = "$VOL_CM" ]; then
    ok "клієнту віддається саме та версія, що записана в описі (${SERVED_VER})"
  elif [ -n "$VOL_CM" ]; then
    fail "опис вказує на ${VOL_CM}, а клієнту віддається ${SERVED_VER}" \
         "копії не перестворилися під новий опис: kubectl rollout status deployment/${APP}"
  fi

  if printf '%s' "$BODY" | grep -q '__POD__'; then
    fail "ім'я копії в сторінку не підставляється" \
         "втрачено ConfigMap rickroll-conf: застосуйте ../01-deploy/rickroll.yaml цілком"
  else
    SERVED_POD="$(printf '%s' "$BODY" | grep -o "${APP}-[a-z0-9]*-[a-z0-9]*" | head -1)"
    if [ -n "$SERVED_POD" ] && kubectl get pod "$SERVED_POD" >/dev/null 2>&1; then
      ok "сторінку віддала жива копія ${SERVED_POD}"
    else
      warn "не вдалося зіставити ім'я зі сторінки з працюючою копією" \
           "ймовірно, копії змінювалися прямо під час перевірки — запустіть скрипт ще раз"
    fi
  fi

  evidence "Віддана сторінка (фрагмент)" \
    "$(printf '%s' "$BODY" | grep -o '<h1>[^<]*</h1>' | head -1)
$(printf '%s' "$BODY" | grep -o "вас обслужив Pod<b>${APP}-[a-z0-9-]*</b>" | head -1)"
fi

# --- готовність до наступних лаб ------------------------------------------
# Лаба піднімала копії до трьох, щоб заміну було видно поштучно. Залишені три
# копії нічого не ламають — звідси warn, а не fail, — але займають місце на навчальному
# вузлі, якого далі не вистачить сусіднім лабам.
if [ "$WANT" = "1" ]; then
  ok "кількість копій повернуто до однієї"
else
  warn "зараз замовлено копій: ${WANT}" \
       "після лаби варто повернути одну: kubectl scale deployment ${APP} --replicas=1"
fi

finish
